const both = ['major_transition', 'career_transition'];
function expand(row, scope, group, sector = null) {
  const [id, parentId, label, question, answerType, flag] = row;
  const path = {
    graduate: 'cross_major_graduate',
    second_degree: 'second_bachelor',
    minor: 'minor',
  }[flag];
  const evidenceLinks = expansionSources
    .filter((s) => s.supports.includes(id))
    .map((s) => ({ sourceId: s.id, quote: s.quote }));
  return {
    id,
    parentId,
    scope,
    group,
    label,
    question,
    nodeType: 'atomic',
    paths: path
      ? [path]
      : scope.length === 1 &&
          scope[0] === 'major_transition' &&
          ![
            'academic_route',
            'institution_name',
            'current_major',
            'target_major',
            'campus_location',
          ].includes(id)
        ? ['campus_transfer']
        : ['any'],
    sectors: sector ? [sector] : ['any'],
    origin: evidenceLinks.length
      ? 'zhihu_discovered'
      : 'common_sense_candidate',
    evidence: evidenceLinks.map((e) => e.sourceId),
    evidenceLinks,
    policy: {
      active: false,
      source_required: true,
      user_unknown: true,
      max_questions: 1,
      answer_type: answerType,
      official_verification: flag === 'official' || Boolean(path),
      voluntary_only: flag === 'voluntary',
      never_infer_from: ['年龄', '性别', '专业名称', '在职或在校身份'],
      ask_when:
        '所选路径相关，且用户尚未明确提供、未跳过；案例原文支持比较此条件。',
      compare_when:
        '双方主体、阶段、时间范围、单位及量表一致或可明确换算；不满足则未知。',
    },
  };
}

